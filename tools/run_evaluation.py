"""Regenerate the Decision Lab evaluation in results/ (no network, no API key). LLM numbers come only from committed recordings.

Usage: python tools/run_evaluation.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ethics_lab.decision import agents, dilemmas, evaluation, llm  # noqa: E402

NAMES = {a["id"]: a["name"] for a in agents.AGENTS}


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def markdown(report):
    consistency, explanations, human, agreement = (report[k] for k in ("consistency", "explanations", "human", "agreement"))
    features = list(dilemmas.FEATURES)
    bases = len(dilemmas.BASES)
    lines = ["# Decision Lab evaluation", "",
             f"Generated by `tools/run_evaluation.py` from engine version `{report['version']}`. "
             f"{bases} base dilemmas and {len(agreement['rows']) - bases} one-feature variants, {len(agreement['rows'])} dilemmas in total. "
             "Every number below is computed by the deterministic agents; nothing is sampled.", "",
             "## 1. Decision consistency", "",
             "Each variant changes exactly one feature in one lane. A change is counted when the agent spares a different group "
             "than in the base dilemma. Pairs where either decision is an exact tie are excluded, because the tie-break, not the rule, decides them. "
             "A violation is a change caused by a feature the rule does not read.", ""]
    rows = []
    for a in agents.AGENTS:
        s = consistency["summary"][a["id"]]
        cells = []
        for f in features:
            b = s["by_feature"][f]
            mark = "S" if b["expected"] == "sensitive" else "I"
            cells.append(f"{mark} {b['changed']}/{b['pairs']}")
        rows.append([a["name"], *cells, s["violations"], s["ties_excluded"]])
    lines += table(["Agent", *features, "violations", "tie pairs excluded"], rows)
    lines += ["", "S = rule reads this feature (expected sensitive); I = rule ignores it (expected invariant). "
              "Cells show changed/pairs.", "",
              "## 2. Explanation faithfulness", "",
              "Checklist per explanation: the stated decision matches the returned choice; every factor whose one-step change would flip "
              "the decision (counterfactual influence) is cited; no factor the rule ignores is cited; every number quoted appears in the calculation "
              "or scenario (±0.05).", ""]
    lines += table(["Agent", "passed", "audited"], [[NAMES[k], v["passed"], v["audited"]] for k, v in explanations["summary"].items()])
    lines += ["", "The deterministic explanations are generated from each agent's trace, so a full pass is a test of the audit and templates, "
              "not evidence that free-text explanations are faithful. The same audit is applied to LLM agents.", "",
              "## 3. Comparison with Moral Machine preference directions", "",
              f"Source: {human['source']}. Each contrast is run with the favoured group in the stay lane and again in the swerve lane.", ""]
    prefs = human["preferences"]
    lines += table(["Feature", "Humans tend to spare", "over", "strength"], [[p["feature"], p["spare"], p["over"], p["strength"]] for p in prefs])
    lines.append("")
    lines += table(["Agent", *[p["feature"] for p in prefs]],
                   [[NAMES[k], *[" / ".join(v[p["feature"]]) for p in prefs]] for k, v in human["summary"].items()])
    lines += ["", "Aligned = spares the group humans tend to spare. Opposed = spares the other group, usually because the lane order or "
              "reference point outweighs the feature. Indifferent = exact tie resolved by the default. These are descriptive survey "
              "directions, not a standard of moral correctness.", "",
              "## 4. Agreement between agents", "",
              f"All four agents spare the same group in {agreement['unanimous']} of {len(agreement['rows'])} dilemmas.", ""]
    split = [r for r in agreement["rows"] if not r["unanimous"] and "~" not in r["dilemma"]]
    if split:
        lines += ["Base dilemmas with disagreement:", ""]
        for r in split:
            d = dilemmas.get(r["dilemma"])
            group = {d[side]["group"]: dilemmas.describe_lane(d[side]) for side in ("stay", "swerve")}
            lines.append(f"- **{d['title']}** (`{d['id']}`): " + "; ".join(f"{NAMES[k]} spares {group[g]}" for k, g in r["spared"].items()))
    lines += llm_section(llm.recorded_summary())
    lines += ["", "## Limits", "",
              "Small authored scenario set; rules and parameters are stated modelling choices (see the report and docs/decision-lab.md); "
              "the Sen agent is Sen-inspired, not a canonical algorithm; human data is used for direction only.", ""]
    return "\n".join(lines)


def llm_section(rec):
    lines = ["", "## 5. LLM agents (recorded runs)", ""]
    if not rec["recordings"]:
        return lines + ["No recordings yet. Run `tools/record_llm.py` with an OpenRouter key to add real runs; nothing is reported until then."]
    lines += [f"{rec['recordings']} real batched runs ({', '.join(f'`{m}`' for m in rec['models'])}, recorded {', '.join(rec['recorded'])}), "
              "one request per dilemma for all four agents. Answers are re-checked against today's rules and audit; their text is never changed.", ""]
    header = ["Agent", "matches rule", "audit passed", "names choice", "cites influential", "no ignored factor", "numbers traceable"]
    keys = ["matches_reference", "audit_passed", "names_its_choice", "cites_influential_factors", "cites_no_ignored_factor", "numbers_traceable"]
    lines += table(header, [[NAMES[a], *[f"{s[k]}/{s['answers']}" for k in keys]] for a, s in rec["summary"].items()])
    return lines + ["", "A small sample of a single free model: this describes these recordings, not language models in general."]


def main():
    report = evaluation.report()
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    (out / "decision_lab.json").write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    (out / "decision_lab.md").write_text(markdown(report), encoding="utf-8")
    (out / "decision_llm.json").write_text(json.dumps(llm.recorded_summary(), indent=1, sort_keys=True), encoding="utf-8")
    total = sum(s["violations"] for s in report["consistency"]["summary"].values())
    print(f"wrote results/decision_lab.md, decision_lab.json and decision_llm.json — {len(report['agreement']['rows'])} dilemmas, {total} consistency violations")


if __name__ == "__main__":
    main()
